// Bundle relative ES modules as a classic script for direct file:// use.
// Each module keeps its own scope; numerical checks can still import sources.
import { readFile, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';
import { posix } from 'node:path';
import { pathToFileURL } from 'node:url';

const site = new URL('../site/', import.meta.url);
export async function buildBundle(entry = 'course-app.js') {
  const sections = new Map();
  async function visit(name) {
    if (sections.has(name)) return;
    sections.set(name,'');
    const source = await readFile(new URL(name, site), 'utf8');
    const dependencies = [];
    const exports = [];
    let classic = source.replace(/^[ \t]*import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"];?[ \t]*\r?$/gm, (_, binding, specifier) => {
      if (!specifier.startsWith('./') && !specifier.startsWith('../')) throw new Error(`External import in ${name}: ${specifier}`);
      const dependency = posix.normalize(posix.join(posix.dirname(name),specifier));
      if (dependency.startsWith('../')) throw new Error(`Import leaves site: ${specifier}`);
      dependencies.push(dependency);
      if (/^\{[\s\S]*\}$/.test(binding.trim())) {
        const names = binding.trim().replace(/\bas\b/g, ':');
        return `const ${names} = __require(${JSON.stringify(dependency)});`;
      }
      const namespace = binding.trim().match(/^\*\s+as\s+(\w+)$/);
      if (namespace) return `const ${namespace[1]} = __require(${JSON.stringify(dependency)});`;
      throw new Error(`Unsupported import binding in ${name}: ${binding}`);
    });
    classic = classic.replace(/^export\s+(?=(?:async\s+)?(?:const|let|function|class)\b)/gm, '');
    for (const match of source.matchAll(/^export\s+(?:async\s+)?(?:const|let|function|class)\s+(\w+)/gm)) exports.push(`${match[1]}:${match[1]}`);
    classic = classic.replace(/^export\s*\{([^}]+)\};?\s*$/gm, (_, list) => {
      for (const item of list.split(',')) {
        const [local, exported = local] = item.trim().split(/\s+as\s+/);
        if (local) exports.push(`${exported}:${local}`);
      }
      return '';
    });
    if (/^\s*(?:import|export)\s/m.test(classic)) throw new Error(`Unsupported module syntax in ${name}`);
    for (const dependency of dependencies) await visit(dependency);
    sections.set(name,`// ${name}\n__factories[${JSON.stringify(name)}] = function(module, exports, __require) {\n${classic.trim()}\nObject.assign(exports,{${exports.join(',')}});\n};`);
  }
  await visit(entry);
  const loader = `const __cache = Object.create(null);\nfunction __require(name) {\n if (__cache[name]) return __cache[name].exports;\n const module = {exports:{}}; __cache[name] = module;\n __factories[name](module,module.exports,__require); return module.exports;\n}`;
  const bundle = `// Generated by node docs/build-kick-site.mjs. Do not edit directly.\n(() => {\n'use strict';\nconst __factories = Object.create(null);\n${[...sections.values()].join('\n\n')}\n${loader}\n__require(${JSON.stringify(entry)});\n})();\n`;
  new Script(bundle, { filename: 'app.bundle.js' });
  return bundle;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const bundle = await buildBundle();
  const target = new URL('app.bundle.js', site);
  // Keep one editable HTML source. The root entry uses the same DOM with
  // relative asset paths adjusted, so ZIP users can open index.html directly.
  const html = await readFile(new URL('index.html', site), 'utf8');
  const entry = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated from site/index.html by npm run build. -->')
    .replace(/\b(src|href)="\.\//g, '$1="./site/');
  const entryTarget = new URL('../index.html', site);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== bundle) {
      throw new Error('app.bundle.js is outdated. Run node docs/build-kick-site.mjs.');
    }
    if (await readFile(entryTarget, 'utf8') !== entry) {
      throw new Error('index.html is outdated. Run npm run build.');
    }
    console.log('app.bundle.js and root index.html are up to date.');
  } else {
    await writeFile(target, bundle);
    await writeFile(entryTarget, entry);
    console.log('Generated site/app.bundle.js and root index.html.');
  }
}
